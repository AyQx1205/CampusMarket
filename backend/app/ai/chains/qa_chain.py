async def answer_rules_question(question: str) -> str:
    """按关键词打分匹配最相关的规则条目；无命中返回兜底话术。"""
    best_answer: str | None = None
    best_score = 0
    for rule in _RULES:
        score = sum(1 for kw in rule["keywords"] if kw in question)
        if score > best_score:
            best_answer, best_score = str(rule["answer"]), score
    return best_answer if best_answer is not None else _FALLBACK
